export type CopyKey = keyof typeof copy;

export function isLang(value: string): value is Lang {
  return order.includes(value as Lang);
}

export function t(lang: string, key: CopyKey, vars?: Record<string, string | number>): string {
  const pack = copy[key];
  const template = (isLang(lang) ? pack[lang] : pack.en) || pack.en;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

